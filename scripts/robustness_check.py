"""How much do randomly missing log lines hurt?  Writes docs/ROBUSTNESS.md.

Benign events of the held-out test days are dropped with probability p (intrusion events are kept, so
recall is not helped or hurt by luck); windows are rebuilt from what is left and scored by the saved model.
    python scripts/robustness_check.py
"""
import random
import sys
from pathlib import Path

import numpy as np

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root))
from seqguard.evaluate import campaign_metrics
from seqguard.loaders import load_sysmon_csv
from seqguard.model import SequenceAnomalyDetector
from seqguard.pipeline import load_config
from seqguard.windows import build_windows

cfg = load_config(root / "configs/sysmon.yaml")
det = SequenceAnomalyDetector.load(root / cfg["output"]["model"])
events = load_sysmon_csv(root / cfg["data"]["events"], "test")
w = cfg["windows"]
rows = []
for p in (0.0, 0.02, 0.05, 0.10):
    fpr, det_rate = [], []
    for seed in range(5):
        r = random.Random(seed)
        kept = [e for e in events if e.label or r.random() >= p]
        wins = build_windows(kept, w["size"], w["stride"], w["idle_gap"])
        s = det.score_windows(wins)
        y = np.array([x.label for x in wins])
        fpr.append(((s >= 0.5) & (y == 0)).sum() / (y == 0).sum())
        c = campaign_metrics(wins, s)
        det_rate.append(c["detected"] / c["campaigns"])
    rows.append((p, np.mean(fpr), np.mean(det_rate)))

lines = ["# Robustness to missing log lines", "",
         "Benign events of the 4 test days are dropped at random (intrusion events are kept); 5 seeds per rate, saved model, threshold unchanged.",
         "Generated by `scripts/robustness_check.py`.", "",
         "| benign lines dropped | false-positive rate (benign windows) | campaigns detected |", "|---|---|---|"]
lines += [f"| {p:.0%} | {f:.1%} | {d:.0%} |" for p, f, d in rows]
lines += ["", "Detection holds, but false positives grow quickly: the bigram sees one step of context, so a missing line makes the next step look out of order.",
          "Collectors that lose lines need a baseline trained on data with the same loss, or a model with longer or skip-gram context (see README, limits)."]
(root / "docs/ROBUSTNESS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
